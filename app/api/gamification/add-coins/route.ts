import { NextResponse } from "next/server"

import { requireUser } from "@/lib/api-auth"
import { getAdminDb } from "@/lib/db-admin"
import { scoreChallengeQuestions } from "@/lib/challenge-scoring"
import type { StoredQuestion } from "@/lib/questions"
import { getSupabaseAdmin } from "@/lib/supabase/admin"

/** Score a weekly challenge from stored answers and grant its prize once. */
export async function POST(request: Request) {
  const gate = await requireUser(request)
  if (!gate.ok) return gate.response
  const body = await request.json().catch(() => null)
  const challengeId = body?.challengeId
  const answers = body?.answers
  const timeTaken = body?.timeTaken
  if (typeof challengeId !== "string" || !/^week-\d{4}-\d{2}-\d{2}-[1-3]$/.test(challengeId)
    || !answers || typeof answers !== "object" || Array.isArray(answers)
    || !Number.isInteger(timeTaken) || timeTaken < 1 || timeTaken > 3600) {
    return NextResponse.json({ error: "Invalid challenge submission." }, { status: 400 })
  }

  try {
    const db = getAdminDb()
    const challengeSnap = await db.collection("challenges").doc(challengeId).get()
    const challenge = challengeSnap.data()
    if (!challengeSnap.exists || !challenge?.autoGenerated) {
      return NextResponse.json({ error: "Challenge unavailable." }, { status: 404 })
    }
    const end = challenge.endDate?.toDate?.() ?? new Date(challenge.endDate)
    if (!Number.isFinite(end.getTime()) || end.getTime() < Date.now()) {
      return NextResponse.json({ error: "Challenge has ended." }, { status: 409 })
    }
    const ids = Object.keys(answers)
    const maxQuestions = Number(challenge.questionCount)
    if (!Number.isInteger(maxQuestions) || maxQuestions < 1 || maxQuestions > 40
      || ids.length !== maxQuestions
      || timeTaken > Number(challenge.timeLimit) + 30
      || ids.some((id) => !/^[\w-]{1,100}$/.test(id))) {
      return NextResponse.json({ error: "Invalid challenge questions." }, { status: 400 })
    }
    const questions = await Promise.all(ids.map((id) => db.collection("practiceQuestions").doc(id).get()))
    const score = scoreChallengeQuestions(
      questions.map((entry) => entry.exists ? entry.data() as StoredQuestion : undefined),
      ids, answers, challenge.subject,
    )
    if (score === null) return NextResponse.json({ error: "Invalid challenge answer." }, { status: 400 })
    const prize = Number(challenge.prize)
    if (!Number.isInteger(prize) || prize < 0 || prize > 100) {
      return NextResponse.json({ error: "Challenge prize unavailable." }, { status: 503 })
    }
    const coins = Math.round(score / ids.length * prize)
    const profile = await db.collection("users").doc(gate.uid).get()
    const { data, error } = await getSupabaseAdmin().rpc("claim_challenge_reward", {
      p_uid: gate.uid,
      p_challenge: challengeId,
      p_score: score,
      p_total: ids.length,
      p_time: timeTaken,
      p_coins: coins,
      p_name: String(profile.data()?.displayName ?? "Student"),
    })
    if (error) throw error
    if (data !== true) return NextResponse.json({ error: "Challenge already claimed." }, { status: 409 })
    return NextResponse.json({ score, total: ids.length, timeTaken, coins })
  } catch (error) {
    console.error("Challenge claim failed:", error)
    return NextResponse.json({ error: "Could not save this challenge. Try again." }, { status: 503 })
  }
}
