/**
 * Seeds the week's three challenges.
 *
 * Two callers, two doors. Vercel cron sends a GET with the scheduler secret;
 * that stays gated by `requireSchedulerOrAdmin`. The challenges page also POSTs
 * here when a student opens it and finds the week empty — the fallback for a
 * cron that never ran — and that POST was gated the same way, so every student
 * who hit it got a 403 in their console and an empty page. Any signed-in
 * account may POST now. It is safe to open because the handler is idempotent
 * (the week's set either exists or is created once), writes only the three
 * global `challenges` documents, and takes nothing from the request body.
 *
 * "Created once" is now literal. `add()` gave each run fresh ids, so two students
 * opening the page in the same second seeded six challenges. The ids are derived
 * from the week, and so are the subjects, so concurrent runs converge on the
 * same three documents instead of racing to duplicate them.
 */
import { NextRequest, NextResponse } from "next/server"

import { requireSchedulerOrAdmin, requireUser } from "@/lib/api-auth"
import { getAdminDb } from "@/lib/db-admin"
import { clientIp, rateLimit } from "@/lib/rate-limit"

const CHALLENGE_SUBJECTS = [
  "Mathematics",
  "English Language",
  "Physics",
  "Chemistry",
  "Biology",
  "Economics",
  "Government",
]

const TEMPLATES = [
  { prefix: "Speed Round", questionCount: 10, timeLimit: 300, prize: 50, desc: "Answer 10 questions in 5 minutes!" },
  { prefix: "Deep Dive", questionCount: 20, timeLimit: 900, prize: 100, desc: "20 challenging questions in 15 minutes." },
  { prefix: "Sprint", questionCount: 5, timeLimit: 120, prize: 30, desc: "Quick 5-question sprint in 2 minutes!" },
]

export async function GET(req: NextRequest) {
  const gate = await requireSchedulerOrAdmin(req)
  if (!gate.ok) return gate.response
  return generateChallenges()
}

export async function POST(req: NextRequest) {
  const gate = await requireUser(req)
  if (!gate.ok) return gate.response

  /* Cheap when the week exists, but still three reads a call. */
  const limit = rateLimit("challenges-generate", clientIp(req), { max: 10, windowMs: 60_000 })
  if (!limit.ok) {
    return NextResponse.json(
      { error: "The week's challenges are being prepared. Try again shortly." },
      { status: 429, headers: { "Retry-After": String(limit.retryAfter) } },
    )
  }

  return generateChallenges()
}

/** Monday 00:00 local to the server, and the Monday after. */
function currentWeek(now: Date) {
  const start = new Date(now)
  const offset = (start.getDay() + 6) % 7 // Sunday belongs to the week that began last Monday
  start.setDate(start.getDate() - offset)
  start.setHours(0, 0, 0, 0)

  const end = new Date(start)
  end.setDate(start.getDate() + 7)
  return { start, end }
}

/** `2026-09-07` — stable for everyone who opens the page this week. */
function weekKey(start: Date) {
  const pad = (n: number) => String(n).padStart(2, "0")
  return `${start.getFullYear()}-${pad(start.getMonth() + 1)}-${pad(start.getDate())}`
}

/** A small deterministic shuffle, so the week's subjects do not depend on who asked first. */
function subjectsFor(key: string): string[] {
  let seed = 0
  for (const char of key) seed = (seed * 31 + char.charCodeAt(0)) >>> 0

  const pool = [...CHALLENGE_SUBJECTS]
  for (let index = pool.length - 1; index > 0; index--) {
    seed = (seed * 1_103_515_245 + 12_345) >>> 0
    const swap = seed % (index + 1)
    ;[pool[index], pool[swap]] = [pool[swap], pool[index]]
  }
  return pool.slice(0, TEMPLATES.length)
}

async function generateChallenges() {
  try {
    const adminDb = getAdminDb()
    const now = new Date()
    const { start, end } = currentWeek(now)
    const key = weekKey(start)
    const subjects = subjectsFor(key)

    let created = 0
    for (let index = 0; index < TEMPLATES.length; index++) {
      const ref = adminDb.collection("challenges").doc(`week-${key}-${index + 1}`)
      const snap = await ref.get()
      if (snap.exists) continue

      const template = TEMPLATES[index]
      const subject = subjects[index]
      await ref.set({
        subject,
        title: `${template.prefix}: ${subject}`,
        description: template.desc,
        questionCount: template.questionCount,
        timeLimit: template.timeLimit,
        prize: template.prize,
        startDate: start,
        endDate: end,
        participantCount: 0,
        createdAt: now,
        autoGenerated: true,
      })
      created++
    }

    return NextResponse.json(
      created === 0
        ? { message: "Challenges already exist for this week", count: 0 }
        : { message: "Weekly challenges generated", count: created },
    )
  } catch (error) {
    console.error("Challenge generation error:", error)
    return NextResponse.json({ error: "Failed to generate challenges" }, { status: 500 })
  }
}
