/**
 * Past questions as a printable PDF, built in the browser with jsPDF.
 *
 * The paper itself is unchanged — question list, then an answer key page, then a
 * footer. What changed is everything around it: the year list was hardcoded
 * 2018–2024 and is now derived from the current year, the two `alert()` calls
 * are in-page messages, and Pro is decided by the shared `isProUser` helper
 * rather than a local `subscription === "pro"` string test that ignored expiry.
 *
 * Reading the questions is no longer done here. A private `optionsOf` returned
 * `[]` for the `[{ id, text }]` shape the AI writes — a paper of questions with
 * no options at all — and printed `451<sub>6</sub>` with its tags. The shared
 * `lib/questions` readers handle every stored shape, and `plainText` turns the
 * markup into something jsPDF's WinAnsi fonts can actually draw: `451_6`, not a
 * subscript glyph it would render as a blank. The answer key goes through
 * `correctLetterOf` too, so a row that stored the answer as the option's full
 * text prints "C" rather than a paragraph.
 */

type Mode = "past_paper" | "topic"

/** Eight years back from today, newest first. */
const YEARS = Array.from({ length: 8 }, (_, index) => String(new Date().getFullYear() - index))

/** Lays the questions out over as many A4 pages as they need, then saves. */
async function buildPdf(questions: StoredQuestion[], title: string, fileName: string) {
  const { jsPDF } = await import("jspdf")
  const pdf = new jsPDF("p", "mm", "a4")
  const margin = 20
  const maxWidth = pdf.internal.pageSize.getWidth() - margin * 2
  let y = 30

  pdf.setFontSize(20)
  pdf.setFont("helvetica", "bold")
  pdf.text(title, margin, y)
  y += 10

  pdf.setFontSize(10)
  pdf.setFont("helvetica", "normal")
  pdf.setTextColor(120)
  pdf.text(
    `AeroLearn • ${questions.length} questions • Generated ${new Date().toLocaleDateString()}`,
    margin,
    y,
  )
  pdf.setTextColor(0)
  y += 15

  pdf.setFontSize(11)
  questions.forEach((question, index) => {
    if (y > 260) {
      pdf.addPage()
      y = 20
    }

    pdf.setFont("helvetica", "bold")
    const lines = pdf.splitTextToSize(
      `${index + 1}. ${plainText(questionText(question))}`,
      maxWidth,
    )
    pdf.text(lines, margin, y)
    y += lines.length * 5 + 3

    pdf.setFont("helvetica", "normal")
    optionsOf(question).forEach((option) => {
      if (y > 270) {
        pdf.addPage()
        y = 20
      }
      const optionLines = pdf.splitTextToSize(
        `   ${option.letter}. ${plainText(option.text)}`,
        maxWidth - 10,
      )
      pdf.text(optionLines, margin + 5, y)
      y += optionLines.length * 5 + 1
    })
    y += 5
  })

  pdf.addPage()
  y = 20
  pdf.setFontSize(16)
  pdf.setFont("helvetica", "bold")
  pdf.text("Answer key", margin, y)
  y += 12
  pdf.setFontSize(10)
  pdf.setFont("helvetica", "normal")

  questions.forEach((question, index) => {
    if (y > 270) {
      pdf.addPage()
      y = 20
    }
    pdf.text(`${index + 1}. ${correctLetterOf(question) || "N/A"}`, margin, y)
    y += 6
  })

  pdf.setFontSize(8)
  pdf.setTextColor(150)
  pdf.text(`Generated by AeroLearn — ${SITE_HOST}`, margin, 285)

  pdf.save(fileName.replace(/\s+/g, "_"))
}

export default function DownloadsPage() {
  const [subjects, setSubjects] = useState<string[]>([])
  const [isPro, setIsPro] = useState(false)
  const [loading, setLoading] = useState(true)

  const [mode, setMode] = useState<Mode>("past_paper")
  const [subject, setSubject] = useState("")
  const [year, setYear] = useState("")
  const [topic, setTopic] = useState("")

  const [generating, setGenerating] = useState(false)
  const [error, setError] = useState("")
  /* Whether `practiceQuestions` has any rows at all — see the note in
     `app/app/mock-exams/page.tsx`. One probe beats letting the student fill in
     the form and read an error that sounds like their typo. */
  const [bankEmpty, setBankEmpty] = useState<boolean | null>(null)

  useEffect(() => {
    const unsubscribe = onAuthStateChanged(auth, async (user) => {
      if (!user) {
        setLoading(false)
        return
      }
      try {
        const snap = await getDoc(doc(db, "users", user.uid))
        const data = snap.exists() ? snap.data() : null
        setSubjects(Array.isArray(data?.subjects) ? (data!.subjects as string[]) : [])
        setIsPro(isProUser(data))

        const probe = await getDocs(query(collection(db, "practiceQuestions"), limit(1)))
        setBankEmpty(probe.empty)
      } catch (err) {
        console.error("Failed to load your plan:", err)
      } finally {
        setLoading(false)
      }
    })
    return () => unsubscribe()
  }, [])

  const download = async () => {
    if (!subject) return

    setError("")
    setGenerating(true)
    try {
      // A topic filter needs both fields; everything else is one equality test,
      // so no composite index is required either way.
      const filters = [where("subject", "==", subject)]
      if (mode === "past_paper" && year) filters.push(where("year", "==", year))
      if (mode === "topic" && topic.trim()) filters.push(where("topic", "==", topic.trim()))

      const snap = await getDocs(query(collection(db, "practiceQuestions"), ...filters))
      const questions = snap.docs.map((d) => ({ id: d.id, ...d.data() }) as StoredQuestion)

      if (questions.length === 0) {
        /* "Check the topic name" blamed the student for an empty library. Say
           which it is: nothing imported at all, or nothing under that filter. */
        setError(
          bankEmpty
            ? "No past questions have been imported into the library yet, so there is nothing to build a paper from."
            : mode === "topic"
              ? `No ${subject} questions have been imported under “${topic.trim()}” yet. Try a broader topic, or download the whole subject.`
              : `No ${subject} questions have been imported${year ? ` for ${year}` : ""} yet.`,
        )
        return
      }

      const title =
        mode === "past_paper"
          ? `${subject} past questions${year ? ` (${year})` : ""}`
          : `${subject} — ${topic.trim()}`
      const fileName =
        mode === "past_paper"
          ? `AeroLearn_${subject}${year ? `_${year}` : ""}_Past_Questions.pdf`
          : `AeroLearn_${subject}_${topic.trim()}.pdf`

      await buildPdf(questions, title, fileName)
    } catch (err) {
      console.error("PDF generation failed:", err)
      setError("The PDF could not be built. Check your connection and try again.")
    } finally {
      setGenerating(false)
    }
  }

  if (loading) return <LoadingState full text="Checking your plan…" />

  const header = (
    <PageHeader
      eyebrow="Offline"
      title="Download past questions"
      subtitle="Build a printable paper from the question bank — questions first, answer key at the back."
    />
  )

  if (!isPro) {
    return (
      <>
        {header}
        <EmptyState
          icon={Lock}
          title="Downloads are a Pro feature"
          description="Pro includes unlimited printable papers for every subject you study. Practice and quizzes stay free."
          actionText="See Pro plans"
          actionHref="/app/upgrade"
        />
      </>
    )
  }

  if (subjects.length === 0) {
    return (
      <>
        {header}
        <EmptyState
          icon={FileDown}
          title="Choose your subjects first"
          description="Papers are built per subject, so pick the ones you are studying and they will appear here."
          actionText="Choose subjects"
          actionHref="/app/settings"
        />
      </>
    )
  }

  const ready = Boolean(subject) && (mode === "past_paper" || topic.trim().length > 1)

  return (
    <>
      {header}

      {bankEmpty && (
        <LibraryPendingNotice
          className="mb-6"
          title="Nothing to download yet"
          detail="No past questions have been imported into the library yet, so a paper built now would come out empty. AI-generated practice covers the same syllabus in the meantime."
        />
      )}

      <section className="card p-5 sm:p-6">
        <Tabs
          className="mb-6"
          ariaLabel="Paper type"
          value={mode}
          onChange={setMode}
          options={[
            { value: "past_paper", label: "Full past paper" },
            { value: "topic", label: "By topic" },
          ]}
        />

        <fieldset>
          <legend className="field-label">Subject</legend>
          <div className="grid grid-cols-2 gap-2 sm:grid-cols-3">
            {subjects.map((name) => (
              <button
                key={name}
                type="button"
                onClick={() => setSubject(name)}
                aria-pressed={subject === name}
                className={cn(
                  "rounded-lg border px-3 py-2.5 text-body-sm font-semibold transition-colors",
                  subject === name
                    ? "border-accent bg-accent/10 text-accent"
                    : "border-hairline bg-surface text-muted hover:bg-surface-hover hover:text-foreground",
                )}
              >
                {name}
              </button>
            ))}
          </div>
        </fieldset>

        {mode === "past_paper" ? (
          <fieldset className="mt-6">
            <legend className="field-label">
              Year <span className="font-normal text-muted">(optional)</span>
            </legend>
            <div className="flex flex-wrap gap-2">
              {[{ value: "", label: "All years" }, ...YEARS.map((y) => ({ value: y, label: y }))].map(
                (option) => (
                  <button
                    key={option.value || "all"}
                    type="button"
                    onClick={() => setYear(option.value)}
                    aria-pressed={year === option.value}
                    className={cn(
                      "rounded-lg border px-3.5 py-2 text-caption font-semibold tabular-nums transition-colors",
                      year === option.value
                        ? "border-accent bg-accent/10 text-accent"
                        : "border-hairline bg-surface text-muted hover:bg-surface-hover hover:text-foreground",
                    )}
                  >
                    {option.label}
                  </button>
                ),
              )}
            </div>
          </fieldset>
        ) : (
          <div className="mt-6">
            <label htmlFor="dl-topic" className="field-label">
              Topic
            </label>
            <div className="relative">
              <Search
                size={17}
                className="pointer-events-none absolute left-3.5 top-1/2 -translate-y-1/2 text-subtle"
                aria-hidden="true"
              />
              <input
                id="dl-topic"
                type="text"
                value={topic}
                onChange={(event) => setTopic(event.target.value)}
                placeholder="e.g. Organic chemistry"
                className="input-premium pl-10"
              />
            </div>
            <p className="field-hint">
              It has to match the topic name on the questions exactly.
            </p>
          </div>
        )}

        {error && (
          <p
            role="alert"
            className="mt-5 rounded-lg border border-danger/35 bg-danger/10 px-4 py-3 text-body-sm font-medium text-danger"
          >
            {error}
          </p>
        )}

        <div className="mt-6 flex flex-wrap items-center gap-x-4 gap-y-3 border-t border-hairline pt-5">
          <button
            type="button"
            onClick={download}
            disabled={generating || !ready}
            className="btn-primary"
          >
            {generating ? (
              <Loader2 className="h-4 w-4 animate-spin" aria-hidden="true" />
            ) : (
              <FileDown className="h-4 w-4" aria-hidden="true" />
            )}
            {generating ? "Building…" : "Download PDF"}
          </button>
          <p className="text-caption text-muted" role={generating ? "status" : undefined}>
            {generating
              ? "Laying out your paper — the file will save itself when it is ready."
              : !subject
                ? "Pick a subject to continue."
                : mode === "topic" && topic.trim().length < 2
                  ? "Type a topic to continue."
                  : "The answer key is on the last page."}
          </p>
        </div>
      </section>
    </>
  )


}

